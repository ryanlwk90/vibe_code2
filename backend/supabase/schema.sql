create table if not exists public.products (
  pid bigint generated by default as identity primary key,
  pname text not null,
  description text not null default '',
  price numeric(12, 2) not null check (price >= 0),
  qty integer not null check (qty >= 0)
);

create table if not exists public.users (
  uid bigint generated by default as identity primary key,
  uname text not null,
  email text not null unique,
  password text not null
);

create table if not exists public.app_accounts (
  account_id bigint generated by default as identity primary key,
  name text not null,
  email text not null unique,
  password_hash text not null,
  role text not null default 'reader' check (role in ('reader', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.app_sessions (
  token_hash text primary key,
  account_id bigint not null references public.app_accounts(account_id) on delete cascade,
  expires_at timestamptz not null
);

create index if not exists app_sessions_expires_at_idx
  on public.app_sessions (expires_at);

create table if not exists public.orders (
  oid bigint generated by default as identity primary key,
  uid bigint not null references public.users(uid) on delete restrict,
  pid bigint not null references public.products(pid) on delete restrict,
  order_date timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.users enable row level security;
alter table public.orders enable row level security;
alter table public.app_accounts enable row level security;
alter table public.app_sessions enable row level security;

create table if not exists public.product_images (
  pid bigint primary key references public.products(pid) on delete cascade,
  mime text not null check (mime in ('image/jpeg','image/png','image/webp')),
  bytes integer not null check (bytes > 0 and bytes <= 204800),
  data bytea not null,
  updated_at timestamptz not null default now()
);

alter table public.product_images enable row level security;
